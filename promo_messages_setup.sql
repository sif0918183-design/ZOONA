-- (اختياري) لضمان توفر دالة توليد المعرّف العشوائي على الإصدارات الأقدم.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- =============================================
-- 1) إنشاء الجدول
-- =============================================
CREATE TABLE IF NOT EXISTS promo_messages (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id      TEXT NOT NULL UNIQUE DEFAULT (gen_random_uuid()::text),
    title          TEXT NOT NULL,
    body           TEXT NOT NULL,
    image_url      TEXT,
    primary_text   TEXT,
    primary_url    TEXT,
    secondary_text TEXT,
    secondary_url  TEXT,
    delay_seconds  INTEGER NOT NULL DEFAULT 10
                   CHECK (delay_seconds >= 0 AND delay_seconds <= 600),
    start_at       TIMESTAMP WITH TIME ZONE,
    end_at         TIMESTAMP WITH TIME ZONE,
    is_active      BOOLEAN NOT NULL DEFAULT true,
    repeat_policy  TEXT NOT NULL DEFAULT 'once'
                   CHECK (repeat_policy IN ('once', '24h', '3d', '7d', 'every_visit')),
    priority       INTEGER NOT NULL DEFAULT 0,
    state_version  INTEGER NOT NULL DEFAULT 1,
    created_at     TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at     TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    CONSTRAINT promo_messages_dates_valid
        CHECK (end_at IS NULL OR start_at IS NULL OR end_at >= start_at)
);

-- إضافة العمود للجداول التي قد تكون أُنشئت سابقاً (آمن لإعادة التنفيذ)
ALTER TABLE promo_messages ADD COLUMN IF NOT EXISTS state_version INTEGER NOT NULL DEFAULT 1;

-- =============================================
-- 2) الفهارس
-- =============================================
CREATE INDEX IF NOT EXISTS idx_promo_messages_active
    ON promo_messages (is_active, priority DESC, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_promo_messages_public_id
    ON promo_messages (public_id);

-- =============================================
-- 3) سياسات RLS
-- =============================================
-- الفكرة الأمنية:
--   * لا يُسمح لأي عميل (anon / authenticated) بعمليات الكتابة إطلاقاً.
--   * القراءة العامة تتم عبر وسيط الـ API فقط (/api/orders?endpoint=promo_messages)
--     الذي يفلتر الرسائل المفعّلة والمؤهلة زمنياً ويعيد حقولاً آمنة فقط،
--     ويستخدم Service Role Key على الخادم (يتجاوز RLS) للعمليات الإدارية.
--   * تُضاف سياسة قراءة عامة للرسائل المفعّلة المؤهلة كطبقة حماية إضافية
--     (بيانات عامة بطبيعتها) دون أي صلاحيات كتابة.
ALTER TABLE promo_messages ENABLE ROW LEVEL SECURITY;

-- إزالة أي سياسات سابقة بنفس الأسماء لضمان أمان إعادة التنفيذ
DROP POLICY IF EXISTS "promo_messages public read active" ON promo_messages;
DROP POLICY IF EXISTS "promo_messages no public write" ON promo_messages;

-- قراءة عامة للرسائل المفعّلة والمؤهلة زمنياً فقط
CREATE POLICY "promo_messages public read active" ON promo_messages
    FOR SELECT
    TO anon
    USING (
        is_active = true
        AND (start_at IS NULL OR start_at <= NOW())
        AND (end_at IS NULL OR end_at >= NOW())
    );

-- ملاحظة: لا تُنشأ أي سياسات INSERT/UPDATE/DELETE، وبالتالي تُرفض أي كتابة
-- مباشرة من الواجهة الأمامية. عمليات الإدارة تتم من الخادم فقط عبر Service Role.

