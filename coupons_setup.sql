-- =============================================
-- Table: coupons
-- =============================================
CREATE TABLE IF NOT EXISTS coupons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT UNIQUE NOT NULL,
    discount_percent NUMERIC NOT NULL CHECK (discount_percent > 0 AND discount_percent <= 100),
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Enable Row Level Security
ALTER TABLE coupons ENABLE ROW LEVEL SECURITY;

-- Policy: Everyone can read active coupons (for checkout verification)
CREATE POLICY "Enable read access for all users on coupons" ON coupons
    FOR SELECT
    USING (true);

-- Policy: Insert/Update/Delete managed via backend API / Admin proxy
CREATE POLICY "Enable insert for authenticated/proxy" ON coupons
    FOR INSERT
    WITH CHECK (true);

CREATE POLICY "Enable update for authenticated/proxy" ON coupons
    FOR UPDATE
    USING (true);

CREATE POLICY "Enable delete for authenticated/proxy" ON coupons
    FOR DELETE
    USING (true);

-- =============================================
-- Alter Table: orders (Add coupon columns if not existing)
-- =============================================
ALTER TABLE orders ADD COLUMN IF NOT EXISTS coupon_code TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS discount_amount NUMERIC DEFAULT 0;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS original_total NUMERIC;

-- Index for coupon lookup by code
CREATE INDEX IF NOT EXISTS idx_coupons_code ON coupons(code);
